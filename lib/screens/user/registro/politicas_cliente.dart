Al crear tu cuenta en Carga Express aceptas estas condiciones:

1. Cómo funciona. Publicas tu envío con el precio que ofreces, los conductores te hacen ofertas y tú eliges una. El precio de la oferta que aceptas es el precio final del viaje.

2. Pago. Le pagas directamente al conductor. Carga Express cobra su comisión al conductor, no a ti.

3. PIN de entrega. Al aceptar una oferta recibes un PIN. Entrégaselo al conductor solo cuando recibas tu carga: sin el PIN el viaje no se puede cerrar.

